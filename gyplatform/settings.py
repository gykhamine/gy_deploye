# ── Concurrence SQLite : mode WAL ───────────────────────────────────────
# Par défaut, SQLite utilise un journal "rollback" : un écrivain bloque
# TOUTE autre connexion (lecteurs compris) pendant sa transaction. Sur le
# dashboard BI, le chargement de la page déclenche potentiellement deux
# écritures proches dans le temps (recalcul des KPI, recalcul des widgets
# graphiques périmés) depuis deux requêtes distinctes : sans ceci, l'une
# des deux peut se heurter à "database is locked" et échouer, d'où le
# besoin de recharger la page plusieurs fois pour que tout finisse par
# passer.
#
# Le mode WAL (Write-Ahead Logging) permet à un écrivain et plusieurs
# lecteurs de cohabiter sans se bloquer (les lecteurs continuent de lire
# l'état précédent pendant que l'écriture est journalisée à part). Combiné
# à busy_timeout (la connexion réessaie au lieu d'échouer immédiatement),
# ça élimine l'essentiel des conflits. Ce qui reste — deux écritures
# strictement simultanées, WAL n'autorisant qu'un seul écrivain à la fois —
# est réglé côté front en séquençant les appels qui écrivent plutôt qu'en
# les lançant en parallèle (voir dashboard_bi.html : chargement du
# dashboard PUIS des KPI, jamais les deux en même temps au démarrage).
from django.db.backends.signals import connection_created


def _activer_wal_sqlite(sender, connection, **kwargs):
    if connection.vendor != 'sqlite':
        return
    with connection.cursor() as curseur:
        curseur.execute('PRAGMA journal_mode=WAL;')
        curseur.execute('PRAGMA synchronous=NORMAL;')
        curseur.execute('PRAGMA busy_timeout=20000;')


connection_created.connect(_activer_wal_sqlite)
