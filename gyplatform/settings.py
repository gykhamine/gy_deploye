# Dans les deux cas, le super-administrateur dispose du bouton « Sauvegarde et restauration » (zip complet) : /plateforme/sauvegarde/.
def _config_base():
    from urllib.parse import unquote, urlparse
    url = os.environ.get("DATABASE_URL", "").strip()
    choix = os.environ.get("GYPLATFORM_BASE", "auto").strip().lower()
    if choix == "auto":
        choix = "postgresql" if (url.startswith(("postgres://", "postgresql://")) or os.environ.get("GYPLATFORM_PG_NOM")) else "sqlite"
    if choix not in ("postgresql", "sqlite", "sqlite_par_entreprise"):
        from django.core.exceptions import ImproperlyConfigured
        raise ImproperlyConfigured("GYPLATFORM_BASE doit valoir auto, postgresql, sqlite ou sqlite_par_entreprise (reçu : %r)" % choix)
    if choix == "postgresql":
        if url.startswith(("postgres://", "postgresql://")):
            u = urlparse(url)
            nom, utilisateur, mdp = unquote(u.path.lstrip("/")), unquote(u.username or ""), unquote(u.password or "")
            hote, port = u.hostname or "localhost", str(u.port or "")
        else:
            nom, utilisateur = os.environ.get("GYPLATFORM_PG_NOM", ""), os.environ.get("GYPLATFORM_PG_UTILISATEUR", "")
            mdp, hote = os.environ.get("GYPLATFORM_PG_MOT_DE_PASSE", ""), os.environ.get("GYPLATFORM_PG_HOTE", "localhost")
            port = os.environ.get("GYPLATFORM_PG_PORT", "")
        return choix, {"ENGINE": "django.db.backends.postgresql", "NAME": nom, "USER": utilisateur, "PASSWORD": mdp,
                       "HOST": hote, "PORT": port, "CONN_MAX_AGE": 60, "OPTIONS": {}}
    return choix, {
        'ENGINE': 'django.db.backends.sqlite3',
        'NAME': BASE_DIR / 'media' / _SYSTEME / 'db.sqlite3',   # la base elle-même est dans le dossier média
        'OPTIONS': {
            # Délai (secondes) qu'une connexion attend, en cas de verrou posé par une autre connexion, avant de lever
            # "database is locked" : au lieu d'échouer instantanément, elle patiente le temps que l'écriture concurrente
            # (ex: recalcul KPI pendant le chargement du dashboard BI) se termine. Défaut de Django : 5 s, portée à 20 s ici.
            'timeout': 20,
        },
    }


