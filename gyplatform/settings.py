def _cle_secrete():
    """Clé secrète : GYPLATFORM_SECRET_KEY, sinon MEDIA_ROOT/systeme/.secret_key (généré UNE fois, droits 600 ; jamais servi par HTTP,
    voir engine/stockage.py). Appelée en fin de fichier, quand MEDIA_ROOT est définitif. Une ancienne clé BASE_DIR/.secret_key est déplacée telle quelle : la changer rendrait
    illisibles les fichiers signés avec elle."""
    cle = os.environ.get("GYPLATFORM_SECRET_KEY", "").strip()
    if cle:
        return cle
    ancien = BASE_DIR / ".secret_key"
    fichier = Path(MEDIA_ROOT) / "systeme" / ".secret_key"
    try:
        return fichier.read_text().strip()
    except OSError:
        pass
    try:
        cle = ancien.read_text().strip()
    except OSError:
        cle = ""
    cle = cle or _secrets.token_urlsafe(64)
    try:
        fichier.parent.mkdir(parents=True, exist_ok=True)
        fd = os.open(str(fichier), os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
        with os.fdopen(fd, "w") as f:
            f.write(cle)
        try:
            ancien.unlink()   # déménagée : plus qu'un seul exemplaire de la clé
        except OSError:
            pass
    except OSError:   # dossier média non inscriptible : repli sur l'ancien emplacement plutôt que de démarrer sans clé stable
        if not ancien.exists():
            ancien.write_text(cle)
            os.chmod(ancien, 0o600)
    return cle


