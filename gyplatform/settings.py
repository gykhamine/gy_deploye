#   GYPLATFORM_SIEM_BRIS_DE_GLACE            noms d'utilisateur jamais verrouillés automatiquement (compte de secours hors ligne)
#   GYPLATFORM_SIEM_URL_SANTE                URL réelle de /sante/ sur le serveur web (surveille le collecteur « web »)
